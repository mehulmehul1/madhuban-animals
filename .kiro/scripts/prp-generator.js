#!/usr/bin/env node

/**
 * PRP Generator - Bridges .claude/commands with Kiro IDE
 * Converts specs to PRPs using existing command methodology
 */

const fs = require('fs');
const path = require('path');

const CLAUDE_COMMANDS_DIR = '.claude/commands';
const PRP_TEMPLATES_DIR = 'PRPs/templates';
const OUTPUT_DIR = 'PRPs';

class PRPGenerator {
  constructor(specFilePath) {
    this.specFilePath = specFilePath;
    this.specContent = fs.readFileSync(specFilePath, 'utf8');
    this.featureName = path.basename(specFilePath, '.spec.md');
  }

  async generatePRP() {
    console.log(`🚀 Generating PRP for: ${this.featureName}`);

    // 1. Load base template
    const baseTemplate = this.loadTemplate('prp_base.md');
    
    // 2. Extract requirements from spec
    const requirements = this.parseSpecRequirements();
    
    // 3. Find relevant Claude commands for context
    const relevantCommands = this.findRelevantCommands();
    
    // 4. Generate PRP content
    const prpContent = this.buildPRPContent(baseTemplate, requirements, relevantCommands);
    
    // 5. Save PRP
    const outputPath = path.join(OUTPUT_DIR, `${this.featureName}.md`);
    fs.writeFileSync(outputPath, prpContent);
    
    console.log(`✅ PRP generated: ${outputPath}`);
    return outputPath;
  }

  loadTemplate(templateName) {
    const templatePath = path.join(PRP_TEMPLATES_DIR, templateName);
    if (fs.existsSync(templatePath)) {
      return fs.readFileSync(templatePath, 'utf8');
    }
    
    // Fallback to basic PRP structure
    return this.getBasicPRPTemplate();
  }

  parseSpecRequirements() {
    // Extract key sections from spec
    const sections = {
      goal: this.extractSection(this.specContent, 'Goal', 'Objective'),
      requirements: this.extractSection(this.specContent, 'Requirements', 'Features'),
      acceptance: this.extractSection(this.specContent, 'Acceptance', 'Done')
    };
    
    return sections;
  }

  findRelevantCommands() {
    const commands = [];
    const commandDirs = ['PRPs', 'development', 'code-quality'];
    
    commandDirs.forEach(dir => {
      const dirPath = path.join(CLAUDE_COMMANDS_DIR, dir);
      if (fs.existsSync(dirPath)) {
        const files = fs.readdirSync(dirPath);
        files.forEach(file => {
          if (file.endsWith('.md')) {
            const content = fs.readFileSync(path.join(dirPath, file), 'utf8');
            commands.push({
              name: file.replace('.md', ''),
              path: path.join(dir, file),
              content: content
            });
          }
        });
      }
    });
    
    return commands;
  }

  buildPRPContent(template, requirements, commands) {
    const timestamp = new Date().toISOString();
    
    return `# PRP: ${this.featureName}

## Meta
- Generated: ${timestamp}
- Source Spec: ${this.specFilePath}
- Generated by: Kiro PRP Generator

## Goal
${requirements.goal || 'Define the specific end state and user value'}

## Why
${this.extractBusinessValue()}

## What - User Visible Behavior
${requirements.requirements || 'Define user-visible behavior and technical requirements'}

## All Needed Context

### Codebase Patterns
${this.generateCodebaseContext()}

### Relevant Commands
${this.generateCommandContext(commands)}

### Validation Strategy
${this.generateValidationGates()}

## Implementation Blueprint

### Pseudocode Approach
\`\`\`
// TODO: Add specific implementation steps
// 1. Analysis phase
// 2. Implementation phase  
// 3. Validation phase
\`\`\`

### Task Breakdown
- [ ] Analyze existing patterns
- [ ] Implement core functionality
- [ ] Add error handling
- [ ] Write tests
- [ ] Run validation gates

## Validation Loop

\`\`\`bash
# Level 1: Syntax & Style
ruff check --fix && mypy .

# Level 2: Unit Tests
uv run pytest tests/ -v

# Level 3: Integration
# Add project-specific commands
\`\`\`

## Quality Score
**Confidence Level**: 7/10 (generated template - needs manual refinement)

## Notes
- This PRP was auto-generated from spec: ${this.specFilePath}
- Review and enhance context sections before execution
- Add specific validation gates for this feature
`;
  }

  extractSection(content, ...sectionNames) {
    for (const name of sectionNames) {
      const regex = new RegExp(`##?\\s*${name}[\\s\\S]*?(?=##|$)`, 'i');
      const match = content.match(regex);
      if (match) {
        return match[0].replace(/##?\\s*${name}/i, '').trim();
      }
    }
    return '';
  }

  extractBusinessValue() {
    // Try to infer business value from spec content
    const valueKeywords = ['value', 'benefit', 'impact', 'user', 'business'];
    const lines = this.specContent.split('\\n');
    
    for (const line of lines) {
      if (valueKeywords.some(keyword => line.toLowerCase().includes(keyword))) {
        return line.trim();
      }
    }
    
    return 'Define the business value and user impact';
  }

  generateCodebaseContext() {
    return `
// TODO: Add specific codebase patterns found during analysis
// Reference existing files that follow similar patterns
// Note any conventions to follow
`;
  }

  generateCommandContext(commands) {
    return commands.slice(0, 3).map(cmd => 
      `- **${cmd.name}**: ${cmd.path}`
    ).join('\\n');
  }

  generateValidationGates() {
    return `
Executable validation commands that the AI agent can run:
- Syntax checking
- Test execution  
- Integration validation
- Code quality checks
`;
  }

  getBasicPRPTemplate() {
    return `# PRP Template
    
## Goal
[Specific end state]

## Why  
[Business value]

## What
[User-visible behavior]

## Context
[All needed context]

## Implementation
[Blueprint with tasks]

## Validation
[Executable commands]
`;
  }
}

// Main execution
if (require.main === module) {
  const specFilePath = process.argv[2];
  
  if (!specFilePath) {
    console.error('Usage: node prp-generator.js <spec-file-path>');
    process.exit(1);
  }

  if (!fs.existsSync(specFilePath)) {
    console.error(`Spec file not found: ${specFilePath}`);
    process.exit(1);
  }

  const generator = new PRPGenerator(specFilePath);
  generator.generatePRP().catch(console.error);
}

module.exports = PRPGenerator;